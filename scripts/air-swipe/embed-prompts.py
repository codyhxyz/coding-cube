"""Embed air swipe's text prompts with eg2cpu, once, for the browser.

The browser only runs EmbeddingGemma 2's image path, so each answer the swipe worker asks
about arrives as one vector: the mean of its prompts' unit embeddings, as hunch.live's
Choice expects. Run it from a hunch checkout, whose workspace provides eg2cpu:

    cd <hunch> && uv run python <coding-cube>/scripts/air-swipe/embed-prompts.py

It writes public/app/air-swipe-prompts.js, which is committed. Only `open_hand` arms a
swipe; the rest are what a hand near a webcam is usually doing instead, so an open palm
has to beat them rather than an empty field.
"""

import json
from pathlib import Path

import numpy as np

from eg2cpu import Model

ANSWERS = {
    "none": [
        "a webcam photo of a person at a desk, hands out of view",
        "a webcam photo of an empty room",
        "a person looking at a computer screen",
    ],
    "open_hand": [
        "an open hand with the palm facing the camera",
        "a hand raised with all five fingers spread",
        "a person holding up an open palm to the webcam",
    ],
    "typing": [
        "a person typing on a keyboard, hands low",
        "hands resting on a laptop keyboard",
    ],
    "fist": [
        "a closed fist",
        "a hand clenched into a fist",
    ],
    "pointing": [
        "a hand pointing with the index finger",
        "one finger raised",
    ],
    "cup": [
        "a person drinking from a cup",
        "a hand holding a mug",
    ],
    "chin": [
        "a person resting their chin on their hand",
        "a hand touching a face",
    ],
}

OUT = Path(__file__).resolve().parents[2] / "public" / "app" / "air-swipe-prompts.js"

model = Model()
vectors = {}
for name, prompts in ANSWERS.items():
    P = np.stack([np.asarray(model.embed(p)[0], np.float32) for p in prompts])
    P /= np.linalg.norm(P, axis=1, keepdims=True)
    vectors[name] = [round(float(v), 6) for v in P.mean(0)]

OUT.write_text(
    "// Generated by scripts/air-swipe/embed-prompts.py: one EmbeddingGemma 2 prompt vector per\n"
    "// answer. Edit the prompts there and run it again rather than editing these numbers.\n"
    f"export default {json.dumps(vectors, separators=(',', ':'))};\n"
)
print(f"{len(vectors)} answers, {len(next(iter(vectors.values())))} dims -> {OUT}")
